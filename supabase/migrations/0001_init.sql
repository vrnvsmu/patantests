-- Server-side grading: client sends question/option IDs; server computes the score.
create or replace function public.submit_attempt(
  p_mode text,
  p_topic_id bigint,
  p_duration_seconds integer,
  p_answers jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_attempt uuid;
  v_total integer;
  v_correct integer;
  v_answer jsonb;
  v_qid uuid;
  v_oid uuid;
  v_is_correct boolean;
begin
  if v_user is null then raise exception 'Authentication required'; end if;
  if p_mode not in ('macro','micro','theory','exam') then raise exception 'Invalid mode'; end if;
  if jsonb_typeof(p_answers) <> 'array' or jsonb_array_length(p_answers) < 1 or jsonb_array_length(p_answers) > 100 then
    raise exception 'Invalid answers';
  end if;

  v_total := jsonb_array_length(p_answers);
  v_correct := 0;

  insert into public.attempts(user_id,mode,topic_id,question_count,correct_count,duration_seconds)
  values(v_user,p_mode,p_topic_id,v_total,0,greatest(0,coalesce(p_duration_seconds,0)))
  returning id into v_attempt;

  for v_answer in select value from jsonb_array_elements(p_answers)
  loop
    v_qid := (v_answer->>'question_id')::uuid;
    v_oid := nullif(v_answer->>'option_id','')::uuid;

    if not exists (
      select 1 from public.questions q
      where q.id = v_qid and q.is_published = true
        and (p_mode <> 'exam' or (q.section = 'macro' and q.is_exam = true))
        and (p_mode not in ('macro','micro','theory') or q.section = p_mode)
    ) then
      raise exception 'Question not available for this mode';
    end if;

    select (a.correct_option_id = v_oid) into v_is_correct
    from public.question_answers a
    where a.question_id = v_qid;

    v_is_correct := coalesce(v_is_correct,false);
    if v_is_correct then v_correct := v_correct + 1; end if;

    insert into public.attempt_answers(attempt_id,question_id,chosen_option_id,is_correct)
    values(v_attempt,v_qid,v_oid,v_is_correct);
  end loop;

  update public.attempts set correct_count = v_correct where id = v_attempt;
  return jsonb_build_object(
    'attempt_id', v_attempt,
    'question_count', v_total,
    'correct_count', v_correct,
    'percent', round(v_correct::numeric * 100 / v_total, 2)
  );
end;
$$;

revoke all on function public.submit_attempt(text,bigint,integer,jsonb) from public;
grant execute on function public.submit_attempt(text,bigint,integer,jsonb) to authenticated;

-- Leaderboard is based on average score across completed attempts, with a minimum of 3 attempts.
create or replace view public.leaderboard as
select
  p.id as user_id,
  p.username,
  p.nickname,
  p.avatar_url,
  count(a.id)::integer as attempts,
  round(avg(a.percent),2) as average_percent,
  coalesce(sum(a.correct_count),0)::bigint as correct_answers,
  max(a.created_at) as last_activity
from public.profiles p
join public.attempts a on a.user_id = p.id
group by p.id,p.username,p.nickname,p.avatar_url
having count(a.id) >= 3;

grant select on public.leaderboard to anon, authenticated;

