create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  nickname text not null,
  avatar_url text,
  created_at timestamptz not null default now(),
  constraint username_format check (username ~ '^[A-Za-z0-9_]{3,24}$'),
  constraint nickname_length check (char_length(nickname) between 2 and 32)
);

create table if not exists public.topics (
  id bigint generated by default as identity primary key,
  block text not null check (block in ('general','specific')),
  title text not null,
  sort_order integer not null default 0,
  unique(block,title)
);

create table if not exists public.questions (
  id uuid primary key default gen_random_uuid(),
  section text not null check (section in ('macro','micro','theory')),
  block text not null check (block in ('general','specific')),
  topic_id bigint references public.topics(id) on delete set null,
  prompt text not null,
  image_path text,
  explanation text,
  is_exam boolean not null default false,
  is_published boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint exam_only_macro check (not is_exam or section = 'macro')
);

create table if not exists public.question_options (
  id uuid primary key default gen_random_uuid(),
  question_id uuid not null references public.questions(id) on delete cascade,
  option_text text not null,
  sort_order integer not null default 0
);

-- Correct answers are kept in a separate table and never exposed by the public question query.
create table if not exists public.question_answers (
  question_id uuid primary key references public.questions(id) on delete cascade,
  correct_option_id uuid not null references public.question_options(id) on delete cascade
);

create table if not exists public.attempts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  mode text not null check (mode in ('macro','micro','theory','exam')),
  topic_id bigint references public.topics(id) on delete set null,
  question_count integer not null check (question_count > 0),
  correct_count integer not null check (correct_count >= 0 and correct_count <= question_count),
  percent numeric(5,2) generated always as (round(correct_count::numeric * 100 / question_count, 2)) stored,
  duration_seconds integer check (duration_seconds is null or duration_seconds >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.attempt_answers (
  id bigint generated by default as identity primary key,
  attempt_id uuid not null references public.attempts(id) on delete cascade,
  question_id uuid not null references public.questions(id) on delete cascade,
  chosen_option_id uuid references public.question_options(id) on delete set null,
  is_correct boolean not null
);

create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create index if not exists questions_published_idx on public.questions(section,block,is_published);
create index if not exists attempts_user_created_idx on public.attempts(user_id,created_at desc);
create index if not exists attempts_score_idx on public.attempts(percent desc, correct_count desc);

